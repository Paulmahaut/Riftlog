-- ============================================
-- V3 — Riftlog v2 schema (see SPEC-v2.md §5)
--
-- Drops the v1 match model. Checked on 2026-11-26: production only held
-- test data (Alice/Bob, fictional legends Ada/Jiro/Kaya, 10 matches).
-- Never edit V1/V2: production already applied them.
-- ============================================

DROP TABLE IF EXISTS match_rounds;
DROP TABLE IF EXISTS matches;
DROP TABLE IF EXISTS decks;
DROP TABLE IF EXISTS players;
DROP TABLE IF EXISTS legends;

ALTER TABLE users ADD COLUMN default_format VARCHAR(3) DEFAULT 'BO3' NOT NULL;

-- --------------------------------------------
-- Reference data, imported from Riftcodex
-- --------------------------------------------
CREATE TABLE
    cards (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        riftbound_id VARCHAR(32) NOT NULL,
        name VARCHAR(255) NOT NULL,
        -- name without "(Signature)", "(Alternate Art)", ... suffixes
        base_name VARCHAR(255) NOT NULL,
        card_type VARCHAR(32) NOT NULL,
        supertype VARCHAR(32),
        set_id VARCHAR(16) NOT NULL,
        -- comma-separated, e.g. "Fury,Order"
        domains VARCHAR(255),
        image_url VARCHAR(1024),
        -- alternate art, overnumbered, signature or promo printing
        variant BOOLEAN NOT NULL,
        -- one canonical printing per (card_type, base_name): what pickers show
        canonical BOOLEAN NOT NULL,
        updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
        CONSTRAINT uk_cards_riftbound_id UNIQUE (riftbound_id)
    );

CREATE INDEX idx_cards_type_canonical ON cards (card_type, canonical);

-- --------------------------------------------
-- Opponents without an account
-- --------------------------------------------
CREATE TABLE
    guest_players (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(100) NOT NULL,
        created_by BIGINT NOT NULL,
        created_at TIMESTAMP WITH TIME ZONE NOT NULL,
        CONSTRAINT fk_guest_players_created_by FOREIGN KEY (created_by) REFERENCES users (id)
    );

-- --------------------------------------------
-- Decks (ids generated by the client)
-- --------------------------------------------
CREATE TABLE
    decks (
        id UUID PRIMARY KEY,
        owner_id BIGINT NOT NULL,
        name VARCHAR(255) NOT NULL,
        legend_card_id BIGINT NOT NULL,
        notes VARCHAR(2000),
        created_at TIMESTAMP WITH TIME ZONE NOT NULL,
        updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
        CONSTRAINT fk_decks_owner FOREIGN KEY (owner_id) REFERENCES users (id),
        CONSTRAINT fk_decks_legend FOREIGN KEY (legend_card_id) REFERENCES cards (id)
    );

CREATE TABLE
    deck_cards (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        deck_id UUID NOT NULL,
        card_id BIGINT NOT NULL,
        zone VARCHAR(16) NOT NULL,
        quantity INT NOT NULL,
        CONSTRAINT fk_deck_cards_deck FOREIGN KEY (deck_id) REFERENCES decks (id) ON DELETE CASCADE,
        CONSTRAINT fk_deck_cards_card FOREIGN KEY (card_id) REFERENCES cards (id),
        CONSTRAINT uk_deck_cards UNIQUE (deck_id, card_id, zone),
        CONSTRAINT ck_deck_cards_quantity CHECK (quantity > 0)
    );

-- --------------------------------------------
-- Matches → games → score events (ids generated by the client)
-- --------------------------------------------
CREATE TABLE
    matches (
        id UUID PRIMARY KEY,
        format VARCHAR(3) NOT NULL,
        source VARCHAR(16) NOT NULL,
        -- id in an external tool (e.g. Riftatlas) for imported matches
        external_id VARCHAR(255),
        recorded_by BIGINT NOT NULL,
        played_at TIMESTAMP WITH TIME ZONE NOT NULL,
        -- NULL = drawn match
        winner_seat INT,
        created_at TIMESTAMP WITH TIME ZONE NOT NULL,
        updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
        CONSTRAINT fk_matches_recorded_by FOREIGN KEY (recorded_by) REFERENCES users (id),
        CONSTRAINT ck_matches_winner_seat CHECK (winner_seat IN (1, 2))
    );

CREATE INDEX idx_matches_played_at ON matches (played_at);

CREATE TABLE
    match_players (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        match_id UUID NOT NULL,
        seat INT NOT NULL,
        user_id BIGINT,
        guest_id BIGINT,
        deck_id UUID,
        legend_card_id BIGINT NOT NULL,
        CONSTRAINT fk_match_players_match FOREIGN KEY (match_id) REFERENCES matches (id) ON DELETE CASCADE,
        CONSTRAINT fk_match_players_user FOREIGN KEY (user_id) REFERENCES users (id),
        CONSTRAINT fk_match_players_guest FOREIGN KEY (guest_id) REFERENCES guest_players (id),
        CONSTRAINT fk_match_players_deck FOREIGN KEY (deck_id) REFERENCES decks (id) ON DELETE SET NULL,
        CONSTRAINT fk_match_players_legend FOREIGN KEY (legend_card_id) REFERENCES cards (id),
        CONSTRAINT uk_match_players_seat UNIQUE (match_id, seat),
        CONSTRAINT ck_match_players_seat CHECK (seat IN (1, 2)),
        CONSTRAINT ck_match_players_identity CHECK (
            (user_id IS NOT NULL AND guest_id IS NULL)
            OR (user_id IS NULL AND guest_id IS NOT NULL)
        )
    );

CREATE INDEX idx_match_players_user ON match_players (user_id);

CREATE TABLE
    games (
        id UUID PRIMARY KEY,
        match_id UUID NOT NULL,
        game_number INT NOT NULL,
        first_seat INT NOT NULL,
        started_at TIMESTAMP WITH TIME ZONE,
        ended_at TIMESTAMP WITH TIME ZONE,
        result VARCHAR(8) NOT NULL,
        end_reason VARCHAR(16) NOT NULL,
        CONSTRAINT fk_games_match FOREIGN KEY (match_id) REFERENCES matches (id) ON DELETE CASCADE,
        CONSTRAINT uk_games_number UNIQUE (match_id, game_number),
        CONSTRAINT ck_games_number CHECK (game_number BETWEEN 1 AND 3),
        CONSTRAINT ck_games_first_seat CHECK (first_seat IN (1, 2))
    );

CREATE TABLE
    game_players (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        game_id UUID NOT NULL,
        seat INT NOT NULL,
        -- derived from score_events for LIVE matches, typed in for MANUAL ones
        final_score INT NOT NULL,
        battlefield_card_id BIGINT,
        mulligan_count INT,
        notes VARCHAR(2000),
        CONSTRAINT fk_game_players_game FOREIGN KEY (game_id) REFERENCES games (id) ON DELETE CASCADE,
        CONSTRAINT fk_game_players_battlefield FOREIGN KEY (battlefield_card_id) REFERENCES cards (id),
        CONSTRAINT uk_game_players_seat UNIQUE (game_id, seat),
        CONSTRAINT ck_game_players_seat CHECK (seat IN (1, 2)),
        CONSTRAINT ck_game_players_mulligan CHECK (mulligan_count BETWEEN 0 AND 2)
    );

CREATE TABLE
    game_side_changes (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        game_id UUID NOT NULL,
        seat INT NOT NULL,
        card_id BIGINT NOT NULL,
        -- +n: card brought in, -n: card taken out
        delta INT NOT NULL,
        CONSTRAINT fk_game_side_changes_game FOREIGN KEY (game_id) REFERENCES games (id) ON DELETE CASCADE,
        CONSTRAINT fk_game_side_changes_card FOREIGN KEY (card_id) REFERENCES cards (id),
        CONSTRAINT ck_game_side_changes_seat CHECK (seat IN (1, 2)),
        CONSTRAINT ck_game_side_changes_delta CHECK (delta <> 0)
    );

CREATE TABLE
    score_events (
        id UUID PRIMARY KEY,
        game_id UUID NOT NULL,
        seq INT NOT NULL,
        seat INT NOT NULL,
        score_type VARCHAR(16) NOT NULL,
        occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
        CONSTRAINT fk_score_events_game FOREIGN KEY (game_id) REFERENCES games (id) ON DELETE CASCADE,
        CONSTRAINT uk_score_events_seq UNIQUE (game_id, seq),
        CONSTRAINT ck_score_events_seat CHECK (seat IN (1, 2))
    );
